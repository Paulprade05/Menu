export function searchCatalogLocally(query: string): MercadonaProduct[] {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();
  const words = q.split(/\s+/).filter(Boolean);

  return MERCADONA_POPULAR_PRODUCTS.filter(prod => {
    const text = `${prod.displayName} ${prod.brand} ${prod.categoryName || ''} ${prod.packaging}`.toLowerCase();
    return words.every(word => text.includes(word));
  });
}
